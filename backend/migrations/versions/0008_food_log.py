VIEW = """
CREATE VIEW food_log_nutrition WITH (security_invoker = true) AS
SELECT
    fl.id                                   AS log_id,
    fl.user_id,
    fl.logged_at,
    fl.recipe_id,
    fl.ingredient_id,
    fl.servings,
    fl.grams,
    COALESCE(r.title, i.canonical_name)     AS name,
    -- recipe: how many lines there are, how many could be computed, whether any is a guess
    agg.lines_total,
    agg.lines_counted,
    CASE WHEN fl.recipe_id IS NULL THEN COALESCE(i.source = 'llm_estimate', false)
         ELSE COALESCE(agg.any_estimate, false) END AS is_estimate,
    CASE WHEN fl.recipe_id IS NULL THEN true
         ELSE agg.lines_counted = agg.lines_total END AS complete,
    CASE WHEN fl.recipe_id IS NULL THEN i.kcal_per_100g * fl.grams / 100
         WHEN agg.lines_counted > 0 THEN agg.kcal * fl.servings / r.servings END    AS kcal,
    CASE WHEN fl.recipe_id IS NULL THEN i.protein_per_100g * fl.grams / 100
         WHEN agg.lines_counted > 0 THEN agg.protein * fl.servings / r.servings END AS protein,
    CASE WHEN fl.recipe_id IS NULL THEN i.fat_per_100g * fl.grams / 100
         WHEN agg.lines_counted > 0 THEN agg.fat * fl.servings / r.servings END     AS fat,
    CASE WHEN fl.recipe_id IS NULL THEN i.carbs_per_100g * fl.grams / 100
         WHEN agg.lines_counted > 0 THEN agg.carbs * fl.servings / r.servings END   AS carbs
FROM food_logs fl
-- A soft-deleted recipe keeps counting: the history of what was eaten does not change.
LEFT JOIN recipes r     ON r.id = fl.recipe_id
LEFT JOIN ingredients i ON i.id = fl.ingredient_id
LEFT JOIN LATERAL (
    SELECT
        count(*)                                     AS lines_total,
        count(*) FILTER (WHERE l.kcal IS NOT NULL)   AS lines_counted,
        sum(l.kcal)                                  AS kcal,
        sum(l.protein)                               AS protein,
        sum(l.fat)                                   AS fat,
        sum(l.carbs)                                 AS carbs,
        bool_or(l.is_estimate) FILTER (WHERE l.kcal IS NOT NULL) AS any_estimate
    FROM recipe_line_nutrition l
    WHERE l.recipe_id = fl.recipe_id AND NOT l.is_optional
) agg ON fl.recipe_id IS NOT NULL
"""


