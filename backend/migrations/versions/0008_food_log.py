"""food log: what a user ate, daily goals, and the food_log_nutrition view

  * users.daily_kcal_goal / daily_protein_goal: the daily targets (NULL = not set).
  * food_logs: one row per thing eaten, EXACTLY one of two kinds, enforced by a CHECK:
    servings of a recipe (recipe_id + servings) or grams of a product (ingredient_id + grams).
    No macros are stored: they are worked out on every read from the current recipe and product
    data, so a correction (a line's weight, a product's values) also corrects the history.
  * Index (user_id, logged_at): "what did I eat on this day" is a range scan on it.
  * Row-Level Security like the recipes, with one addition: the WITH CHECK also demands that the
    recipe / product is visible to the user. A foreign key alone is not enough, because FK checks
    bypass RLS and would accept a guessed id of someone else's private recipe.
  * food_log_nutrition: for every log row the name and the nutrition it contributes. A recipe
    entry is the recipe's (non-optional) lines, summed, times servings eaten / servings of the
    recipe. WITH (security_invoker) so RLS still applies through the view.

Revision ID: 0008
Revises: 0007
Create Date: 2026-11-02

"""

